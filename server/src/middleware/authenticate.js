import { verifySession } from '../../helpers/session.js'

// ─────────────────────────────────────────────────────────────────────────────
// authenticate  —  хүсэлт нэвтэрсэн хэрэглэгчээс ирж байгааг шалгана
// ─────────────────────────────────────────────────────────────────────────────
//
// Хэрхэн ажилладаг вэ:
//   1. Frontend нь нэвтэрсний дараа сессийн токеныг localStorage-д хадгална.
//   2. API хүсэлт бүрт токеныг HTTP header дотор илгээнэ:
//        Authorization: Bearer <token>
//   3. Энэ middleware тэр токеныг уншаад мэдээллийн санд хайна.
//   4. Токен хүчинтэй бөгөөд хугацаа дуусаагүй бол хэрэглэгчийг `req.user` дотор хадгална
//      ингэснээр дараа нь route handler нар хэн хүсэлт гаргаж байгааг мэдэх болно.
//   5. Токен байхгүй эсвэл хүчингүй бол хүсэлтийг шууд зогсоож
//      401 Unauthorized буцаана.
//
// Хэрэглэх арга — нэвтэрсэн хэрэглэгч шаардлагатай маршрутын өмнө тавина:
//   router.post('/', authenticate, (req, res) => { ... })
//
export function authenticate(req, res, next) {
  // Authorization header ийм харагддаг:  "Bearer abc123token"
  // Зайгаар хуваагаад хоёр дахь хэсгийг (index 1) авна.
  const authHeader = req.headers['authorization'] || ''
  const token = authHeader.startsWith('Bearer ') ? authHeader.slice(7) : null

  // Токен огт байхгүй → хэрэглэгч нэвтрээгүй байна
  if (!token) {
    return res.status(401).json({ error: 'Нэвтрэх шаардлагатай' })
  }

  // Токеныг sessions хүснэгтэд хайна (users-тай нэгдүүлсэн)
  const session = verifySession(token)

  // Токен олдсонгүй эсвэл хугацаа дуусчихсан
  if (!session) {
    return res.status(401).json({ error: 'Сессий дууссан эсвэл буруу токен' })
  }

  // Хэрэглэгчийн мэдээллийг хүсэлтэд хавсаргана, route handler нар ашиглаж болно
  // жишээ нь  req.user.id, req.user.username, req.user.role
  req.user = {
    id:       session.user_id,
    username: session.username,
    email:    session.email,
    role:     session.role,
  }

  // Бүх зүйл сайн байна — жинхэнэ route handler руу үргэлжлүүлнэ
  next()
}

// ─────────────────────────────────────────────────────────────────────────────
// canModify  —  нэвтэрсэн хэрэглэгч засах эсвэл устгахыг хүсэж буй нөөцийнхөө
//               эзэмшигч мөн эсэхийг шалгана
// ─────────────────────────────────────────────────────────────────────────────
//
// Хэрхэн ажилладаг вэ:
//   Шалгалт ба тэмцээний мөр бүр `created_by` баганатай байдаг бөгөөд
//   тэрийг үүсгэсэн хэрэглэгчийн id-г хадгалдаг.
//   Энэ функц `created_by` нь `req.user.id`-тэй таарч байгааг шалгана.
//   Админ шалгалтыг алгасаж ямар ч мөрийг засаж болно.
//
// Параметрүүд:
//   row  — энэ функцийг дуудахаасаа өмнө авсан мэдээллийн сангийн мөр
//
// Буцаана:
//   true  — хэрэглэгч үргэлжлүүлэхийг зөвшөөрнө
//   false — хэрэглэгч 403 Forbidden хариу авна
//
export function canModify(row, user) {
  // Админ бүгдийг хийж болно
  if (user.role === 'admin') return true

  // Энгийн хэрэглэгч зөвхөн өөрийн үүсгэсэн мөрийг засаж болно
  // (created_by null бол системийн seed өгөгдөл — хамгаална)
  return row.created_by === user.id
}
